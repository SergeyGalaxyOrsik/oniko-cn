//! Renders the project stylesheet block written by `oniko init`: shared base
//! CSS, theme tokens for light / dark, the Tailwind `@theme inline` mapping and
//! base-layer defaults (same token layout as shadcn/ui on Tailwind v4).

use std::fmt::Write;

use crate::CssVars;

pub const BEGIN_MARKER: &str = "/* oniko-cn:begin";
pub const END_MARKER: &str = "/* oniko-cn:end */";

const RADIUS_SCALE: &[(&str, &str)] = &[
    ("sm", "calc(var(--radius) * 0.6)"),
    ("md", "calc(var(--radius) * 0.8)"),
    ("lg", "var(--radius)"),
    ("xl", "calc(var(--radius) * 1.4)"),
    ("2xl", "calc(var(--radius) * 1.8)"),
    ("3xl", "calc(var(--radius) * 2.2)"),
    ("4xl", "calc(var(--radius) * 2.6)"),
];

pub fn render_block(base_css: &str, vars: &CssVars) -> String {
    let mut css = String::new();
    let _ = writeln!(
        css,
        "{BEGIN_MARKER}: generated by `oniko init`, re-run it to regenerate this block. */"
    );
    css.push_str(base_css.trim());
    css.push_str("\n\n");

    write_rule(&mut css, ":root", vars.light.iter());
    write_rule(&mut css, ".dark", vars.dark.iter());

    css.push_str("@theme inline {\n");
    for (name, value) in &vars.theme {
        let _ = writeln!(css, "  --{name}: {value};");
    }
    let color_names = vars
        .light
        .keys()
        .chain(vars.dark.keys())
        .filter(|n| *n != "radius");
    let mut seen = std::collections::BTreeSet::new();
    for name in color_names {
        if seen.insert(name) {
            let _ = writeln!(css, "  --color-{name}: var(--{name});");
        }
    }
    if vars.light.contains_key("radius") {
        for (size, value) in RADIUS_SCALE {
            let _ = writeln!(css, "  --radius-{size}: {value};");
        }
    }
    css.push_str("}\n\n");

    css.push_str(
        "@layer base {\n  * {\n    @apply border-border outline-ring/50;\n  }\n  body {\n    @apply bg-background text-foreground;\n  }\n}\n",
    );
    css.push_str(END_MARKER);
    css.push('\n');
    css
}

fn write_rule<'a>(
    css: &mut String,
    selector: &str,
    vars: impl Iterator<Item = (&'a String, &'a String)>,
) {
    let _ = writeln!(css, "{selector} {{");
    for (name, value) in vars {
        let _ = writeln!(css, "  --{name}: {value};");
    }
    css.push_str("}\n\n");
}

/// Replaces the generated block in `existing` (or appends it), and makes sure
/// the stylesheet imports Tailwind.
pub fn upsert_block(existing: &str, block: &str) -> String {
    let mut out = match (existing.find(BEGIN_MARKER), existing.find(END_MARKER)) {
        (Some(start), Some(end)) if end > start => {
            let end = end + END_MARKER.len();
            let end = existing[end..].strip_prefix('\n').map_or(end, |_| end + 1);
            format!("{}{}{}", &existing[..start], block, &existing[end..])
        }
        _ if existing.trim().is_empty() => block.to_string(),
        _ => format!("{}\n\n{}", existing.trim_end(), block),
    };
    if !out.contains("@import \"tailwindcss\"") {
        out = format!("@import \"tailwindcss\";\n\n{out}");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vars() -> CssVars {
        let mut vars = CssVars::default();
        vars.light.insert("radius".into(), "0.625rem".into());
        vars.light
            .insert("primary".into(), "oklch(0.205 0 0)".into());
        vars.dark
            .insert("primary".into(), "oklch(0.922 0 0)".into());
        vars
    }

    #[test]
    fn renders_tokens_and_theme_mapping() {
        let css = render_block("@custom-variant dark (&:is(.dark *));", &vars());
        assert!(css.contains(":root {\n  --primary: oklch(0.205 0 0);\n  --radius: 0.625rem;\n}"));
        assert!(css.contains(".dark {\n  --primary: oklch(0.922 0 0);\n}"));
        assert!(css.contains("--color-primary: var(--primary);"));
        assert!(!css.contains("--color-radius"));
        assert!(css.contains("--radius-4xl: calc(var(--radius) * 2.6);"));
    }

    #[test]
    fn upsert_is_idempotent_and_keeps_user_css() {
        let block = render_block("", &vars());
        let first = upsert_block("body { margin: 0; }\n", &block);
        assert!(first.starts_with("@import \"tailwindcss\";"));
        assert!(first.contains("body { margin: 0; }"));
        let second = upsert_block(&first, &block);
        assert_eq!(first, second);
    }
}
